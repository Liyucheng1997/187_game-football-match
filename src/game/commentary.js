export function say(key, vars = {}) {
  const arr = L[key];
  if (!arr) return '';
  let s = arr[(Math.random() * arr.length) | 0];
  for (const k in vars) s = s.replaceAll('{' + k + '}', vars[k]);
  return s;
}
